from datetime import datetime

from sqlalchemy import (
    Column,
    Integer,
    String,
    Text,
    DateTime,
    ForeignKey,
    JSON,
    Float
)

from database import Base


# =========================================================
# USER
# =========================================================

class User(Base):

    __tablename__ = "users"

    id = Column(
        Integer,
        primary_key=True
    )

    username = Column(
        String(50),
        unique=True
    )

    email = Column(
        String(100),
        unique=True
    )

    password_hash = Column(
        String(255)
    )


# =========================================================
# CONVERSATION
# =========================================================

class Conversation(Base):

    __tablename__ = "conversations"

    id = Column(
        Integer,
        primary_key=True
    )

    user_id = Column(
        Integer,
        ForeignKey("users.id")
    )

    title = Column(
        String(255)
    )

    system_prompt = Column(
        Text
    )


# =========================================================
# MESSAGE
# =========================================================

class Message(Base):

    __tablename__ = "messages"

    id = Column(
        Integer,
        primary_key=True
    )

    conversation_id = Column(
        Integer,
        ForeignKey("conversations.id")
    )

    role = Column(
        String(20)
    )

    content = Column(
        Text
    )

    # Nullable for legacy messages and messages outside tracked episodes.
    episode_id = Column(
        String(20),
        ForeignKey("episodes.episode_id"),
        nullable=True,
        index=True
    )


# =========================================================
# EPISODE
# =========================================================

class Episode(Base):

    __tablename__ = "episodes"

    id = Column(
        Integer,
        primary_key=True,
        index=True
    )

    episode_id = Column(
        String(20),
        unique=True,
        nullable=False
    )

    user_id = Column(
        Integer,
        ForeignKey("users.id"),
        nullable=False
    )

    title = Column(
        String(255),
        nullable=False
    )

    summary = Column(
        Text,
        nullable=True
    )

    status = Column(
        String(20),
        default="ACTIVE",
        nullable=False
    )

    # MySQL UNIQUE permits multiple NULLs. Setting this to user_id only
    # while ACTIVE enforces at most one active episode per user.
    active_user_id = Column(
        Integer,
        ForeignKey("users.id"),
        unique=True,
        nullable=True
    )

    created_at = Column(
        DateTime,
        default=datetime.utcnow
    )

    updated_at = Column(
        DateTime,
        default=datetime.utcnow,
        onupdate=datetime.utcnow
    )

    closed_at = Column(
        DateTime,
        nullable=True
    )

    messages_since_last_mood = Column(
        Integer,
        default=0,
        nullable=False
    )

    messages_since_last_reflection = Column(
        Integer,
        default=0,
        nullable=False
    )


# =========================================================
# EPISODE MOOD
# =========================================================

class EpisodeMood(Base):

    __tablename__ = "episode_moods"

    id = Column(
        Integer,
        primary_key=True,
        index=True
    )

    episode_id = Column(
        String(20),
        ForeignKey("episodes.episode_id"),
        nullable=False
    )

    mood = Column(
        String(100),
        nullable=False
    )

    message_id = Column(
        Integer,
        ForeignKey("messages.id"),
        nullable=True,
        unique=True
    )

    confidence = Column(Float, nullable=True)
    evidence = Column(Text, nullable=True)

    created_at = Column(
        DateTime,
        default=datetime.utcnow
    )


