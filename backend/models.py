# =========================================================
# LONG-TERM MEMORY
# =========================================================

class LongTermMemory(Base):

    __tablename__ = "long_term_memory"

    id = Column(
        Integer,
        primary_key=True,
        autoincrement=True
    )

    user_id = Column(
        Integer,
        ForeignKey("users.id"),
        nullable=False,
        unique=True
    )

    # Complete consolidated memory generated by the LLM.
    memory = Column(
        Text,
        nullable=False
    )

    # LLM-generated Profile themes.
    #
    # Example:
    # [
    #     {
    #         "id": "theme_01",
    #         "category": "Feeling",
    #         "title": "Anxious",
    #         "summary": "Worries about the future...",
    #         "details": "Full supporting memory...",
    #         "tone": "amber"
    #     }
    # ]
    #
    # Stored as JSON so React can directly render the themes.

    profile_themes = Column(
        JSON,
        nullable=True
    )

    updated_at = Column(
        DateTime,
        default=datetime.utcnow,
        onupdate=datetime.utcnow
    )






# =========================================================
# DETECTED PATTERNS
# =========================================================

class EpisodePattern(Base):
    __tablename__ = "episode_patterns"

    id = Column(Integer, primary_key=True, autoincrement=True)
    pattern_id = Column(String(40), unique=True, nullable=False)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False, index=True)
    category = Column(String(80), nullable=False, default="general")
    description = Column(Text, nullable=False)
    confidence = Column(Float, nullable=False)
    evidence = Column(JSON, nullable=False)
    status = Column(String(20), nullable=False, default="ACTIVE")
    first_seen_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    last_seen_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)
